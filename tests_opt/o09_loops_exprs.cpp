#include <iostream>
using namespace std;
int main() {
    int s = 0;
    for (int i = 0 + 0; i < 2 * 5; i = i + 1) {
        s = s + i * 1 + (i + 0) * 2;
        if (i * 0 == 0 && s > 100 - 90) s = s - 1;
    }
    int j = 10;
    while (j > 0 + 0) { j = j - 3; }
    do { s = s + 1; } while (s < 40 + 2);
    cout << s << j << endl;
    return 0;
}
